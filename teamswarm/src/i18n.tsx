type Values = Record<string, string | number>;
const enLabels: Record<string, string> = {
  "insight.proposed": "Proposed",
  "insight.adopted": "Adopted",
  "insight.rejected": "Rejected",
  "insight.superseded": "Superseded",
  self_checked: "Self-checked",
};
export function translator(language: Language) {
  return (key: string, values: Values = {}) =>
    (language === "zh-CN" ? zhCN[key] || key : enLabels[key] || key).replace(
      /\{(\w+)\}/g,
      (match, name: string) => String(values[name] ?? match),
    );
}
const LanguageContext = createContext({
  language: "en" as Language,
  locale: "en-US",
  t: translator("en"),
});
export function LanguageProvider({
  language,
  children,
}: {
  language: Language;
  children: ReactNode;
}) {
  const value = useMemo(
    () => ({
      language,
      locale: language === "zh-CN" ? "zh-CN" : "en-US",
      t: translator(language),
    }),
    [language],
  );
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}
export const useI18n = () => useContext(LanguageContext);
